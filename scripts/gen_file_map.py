#!/usr/bin/env python3
"""gen_file_map.py - write docs/FILE_MAP.md: every file in the repo and what it is.

Run from the repo root:  python scripts/gen_file_map.py
For Verilog/VHDL/Python/Tcl/shell sources the description is taken from the
file's own header comment, so the map stays correct when files change.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {".git", "run", "build", "vivado", "__pycache__"}

FOLDERS = {
    "prompts": "The engineering briefs and roadmaps given to the AI assistant (the original prompts).",
    "docs": "Repo-level documentation: build history, controls, team split, this file map.",
    "scripts": "Repo maintenance scripts.",
    "keylight": "KeyLight: piano rhythm game (vertical slice).",
    "strikeline": "StrikeLine: mouse-swipe ten-pin bowling (v2 = this commit, v1 = tag strikeline-v1.0).",
    "rtl/top": "Top level, shared contract header, clocks/ticks, pixel coordinates, shared helpers.",
    "rtl/provided": "Course-provided files, unchanged (OLED driver, PS/2 mouse controller).",
    "rtl/a_gesture": "Student A - mouse input and swipe-gesture recognition.",
    "rtl/b_ball": "Student B - ball physics, lane, camera, first-person view.",
    "rtl/c_pins": "Student C - pin physics, pin-setter, settle and split detection.",
    "rtl/d_game_ui": "Student D - game FSMs, scoring, menus/HUD, text engine, flash save.",
    "rtl/a_sound": "Student A - sound engine.",
    "rtl/b_input_freeplay_storage": "Student B - inputs, Free Play.",
    "rtl/c_game": "Student C - rhythm game engine.",
    "rtl/d_ui_learn": "Student D - UI, mode FSM, Learn mode.",
    "sim": "Self-checking testbenches (+ models) and the simulation scripts.",
    "data": "Generated ROM contents ($readmemh). Regenerate with tools/make_data.py.",
    "text": "Hand-written fonts and on-screen strings (inputs of the data tools).",
    "songs": "Songs as text (KeyLight).",
    "tools": "Table/font/string generators and Vivado build scripts.",
    "constraints": "Basys3 pin and timing constraints (XDC).",
}

HEADER = re.compile(r"^\s*(?://|#|--)\s*(?:=+)?\s*([\w./-]+\.(?:v|vh|vhd|py|tcl|sh))\s*[:\-]\s*(.+)$")


def describe(path):
    name = os.path.basename(path)
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            lines = [next(fh, "") for _ in range(25)]
    except OSError:
        return ""
    for ln in lines:
        m = HEADER.match(ln)
        if m and m.group(1).endswith(name):
            return m.group(2).strip()
    for ln in lines:                                    # python docstrings
        s = ln.strip().strip('"').strip()
        if s.startswith(name) and " - " in s:
            return s.split(" - ", 1)[1]
    if name.endswith(".png"):
        return "OLED screenshot captured from the real design by sim/top/tb_screens.v"
    if name == "strings_map.vh":
        return "generated by tools/strings_to_mem.py: address and length of every on-screen string"
    if name in ("Oled_Display.v", "Mouse_Control.vhd", "Ps2Interface.vhd"):
        return "course-provided file (EE2026 template), used unchanged"
    if name.endswith(".mem"):
        return "generated ROM data"
    if name.endswith(".md"):
        first = next((l.strip("# \n") for l in lines if l.startswith("#")), "")
        return first
    if name.endswith(".txt"):
        return "text input for a generator"
    if name.endswith(".xdc"):
        return "pin and timing constraints"
    return ""


def main():
    out = ["# File map", "",
           "Generated by `scripts/gen_file_map.py` from each file's header comment. "
           "Folders first, then every file with its one-line purpose.", "",
           "## Repo root", "",
           "| File | Purpose |", "|---|---|",
           "| `README.md` | Overview: both games, features, releases, how it was prompted, team split |",
           "| `CLAUDE.md` | Entry point for AI agents: what to read, commands, gotchas |",
           "| `AGENTS.md` | Pointer to CLAUDE.md for other agents |",
           "| `.gitignore`, `.gitattributes` | Ignore build outputs; LF line endings, binary .png/.bit |", ""]
    for top in ["prompts", "docs", "scripts", "strikeline", "keylight"]:
        out.append("## `%s/` - %s" % (top, FOLDERS[top]))
        out.append("")
        base = os.path.join(ROOT, top)
        for d, dirs, files in os.walk(base):
            dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
            rel = os.path.relpath(d, ROOT).replace(os.sep, "/")
            sub = rel.split("/", 1)[1] if "/" in rel else ""
            if files:
                note = FOLDERS.get(sub, "")
                out.append("### `%s/`%s" % (rel, (" - " + note) if note else ""))
                out.append("")
                out.append("| File | Purpose |")
                out.append("|---|---|")
                for f in sorted(files):
                    out.append("| `%s` | %s |" % (f, describe(os.path.join(d, f)).replace("|", "/")))
                out.append("")
    with open(os.path.join(ROOT, "docs", "FILE_MAP.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("docs/FILE_MAP.md written")


if __name__ == "__main__":
    main()
