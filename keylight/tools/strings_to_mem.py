#!/usr/bin/env python3
"""strings_to_mem.py - build the string ROM used by every screen.

Owner: Student D.
Input : text/strings.txt, data/song_titles.txt (from song_to_mem.py)
Output: data/strings.mem       one 6-bit glyph code per line (hex)
        rtl/d_ui_learn/strings_map.vh
            `define S_<NAME> <address>   start of the string
            `define L_<NAME> <length>    characters (or item width for LISTs)
Glyph code = ASCII - 0x20, matching font_to_mem.py.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROM_DEPTH = 1024


def code(ch):
    c = ord(ch.upper())
    if not 0x20 <= c <= 0x5F:
        raise ValueError("character '%s' has no glyph" % ch)
    return c - 0x20


def main():
    entries = []                      # (name, text, width)
    with open(os.path.join(ROOT, "text", "strings.txt")) as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("//"):
                continue
            m = re.fullmatch(r'LIST\s+(\w+)\s+(\d+)\s*=\s*(.*)', line)
            if m:
                width = int(m.group(2))
                items = re.findall(r'"([^"]*)"', m.group(3))
                for it in items:
                    if len(it) > width:
                        raise ValueError("%s item '%s' wider than %d" % (m.group(1), it, width))
                entries.append((m.group(1), "".join(it.ljust(width) for it in items), width))
                continue
            m = re.fullmatch(r'(\w+)\s*=\s*"([^"]*)"', line)
            if not m:
                raise ValueError("cannot parse: %s" % line)
            entries.append((m.group(1), m.group(2), len(m.group(2))))

    titles = open(os.path.join(ROOT, "data", "song_titles.txt")).read().split("\n")
    titles = [t for t in titles if t] + ["MY SONG"]
    entries.append(("SONGS", "".join(t[:12].ljust(12) for t in titles), 12))

    rom, defs = [], []
    for name, text, width in entries:
        defs.append("`define S_%-8s 10'd%d" % (name, len(rom)))
        defs.append("`define L_%-8s %d" % (name, width))
        rom += [code(c) for c in text]
    used = len(rom)
    if used > ROM_DEPTH:
        raise ValueError("string ROM overflow: %d > %d" % (used, ROM_DEPTH))
    rom += [0] * (ROM_DEPTH - used)

    with open(os.path.join(ROOT, "data", "strings.mem"), "w") as fh:
        fh.write("\n".join("%02X" % c for c in rom) + "\n")
    with open(os.path.join(ROOT, "rtl", "d_ui_learn", "strings_map.vh"), "w") as fh:
        fh.write("// GENERATED by tools/strings_to_mem.py from text/strings.txt - do not edit.\n")
        fh.write("`ifndef STRINGS_MAP_VH\n`define STRINGS_MAP_VH\n")
        fh.write("\n".join(defs) + "\n`endif\n")
    print("strings.mem: %d of %d characters used" % (used, ROM_DEPTH))


if __name__ == "__main__":
    try:
        main()
    except ValueError as err:
        sys.exit("strings_to_mem: %s" % err)
