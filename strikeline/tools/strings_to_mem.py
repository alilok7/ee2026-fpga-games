#!/usr/bin/env python3
"""strings_to_mem.py - build the string ROM used by every text layer (A and D).

Owner: Student D.
Input : text/strings.txt
Output: data/strings.mem            one 6-bit glyph code per line (hex), 2048 lines
        rtl/d_game_ui/strings_map.vh
            `define S_<NAME> <address>   first character
            `define L_<NAME> <length>    characters (item width for a LIST)
Also builds Student C's second-screen ROM the same way:
        text/screen2_strings.txt -> data/screen2_strings.mem (512 lines)
                                 -> rtl/c_pins/screen2_map.vh  (`define S2_<NAME>, L2_<NAME>)
Syntax of strings.txt:
    NAME = "text"
    LIST NAME width = "a", "b", ...      item i starts at S_NAME + i * width
Glyph code = ASCII - 0x20 (matches fonts_to_mem.py).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROM_DEPTH = 2048

# (text file, mem file, map file, define prefix, ROM depth)
ROMS = [
    ("strings.txt", "strings.mem", ("d_game_ui", "strings_map.vh"), "", 2048),
    ("screen2_strings.txt", "screen2_strings.mem", ("c_pins", "screen2_map.vh"), "2", 512),
    # screen 2's ROM is 512 deep: string_rom #(.AW(9)) in rtl/c_pins/screen2.v
]


def code(ch):
    c = ord(ch.upper())
    if not 0x20 <= c <= 0x5F:
        raise ValueError("character '%s' has no glyph" % ch)
    return c - 0x20


def build(src, mem, vh, pre, depth):
    entries = []
    with open(os.path.join(ROOT, "text", src)) as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("//"):
                continue
            m = re.fullmatch(r'LIST\s+(\w+)\s+(\d+)\s*=\s*(.*)', line)
            if m:
                width = int(m.group(2))
                items = re.findall(r'"([^"]*)"', m.group(3))
                for it in items:
                    if len(it) > width:
                        raise ValueError("%s item '%s' wider than %d" % (m.group(1), it, width))
                entries.append((m.group(1), "".join(it.ljust(width) for it in items), width))
                continue
            m = re.fullmatch(r'(\w+)\s*=\s*"([^"]*)"', line)
            if not m:
                raise ValueError("cannot parse: %s" % line)
            entries.append((m.group(1), m.group(2), len(m.group(2))))

    rom, defs = [], []
    for name, text, width in entries:
        defs.append("`define S%s_%-8s 11'd%d" % (pre, name, len(rom)))
        defs.append("`define L%s_%-8s %d" % (pre, name, width))
        rom += [code(c) for c in text]
    used = len(rom)
    if used > depth:
        raise ValueError("%s: string ROM overflow: %d > %d" % (src, used, depth))
    rom += [0] * (depth - used)
    with open(os.path.join(ROOT, "data", mem), "w") as fh:
        fh.write("\n".join("%02X" % c for c in rom) + "\n")
    guard = vh[1].upper().replace(".", "_")
    with open(os.path.join(ROOT, "rtl", vh[0], vh[1]), "w") as fh:
        fh.write("// GENERATED by tools/strings_to_mem.py from text/%s - do not edit.\n" % src)
        fh.write("`ifndef %s\n`define %s\n" % (guard, guard))
        fh.write("\n".join(defs) + "\n`endif\n")
    print("%-20s %d of %d characters used" % (mem, used, depth))


def main():
    for rom in ROMS:
        build(*rom)


if __name__ == "__main__":
    try:
        main()
    except ValueError as err:
        sys.exit("strings_to_mem: %s" % err)
